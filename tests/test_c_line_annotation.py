"""Tests for the C-source-line annotation of the C compilers (toycc + minicc).

Both compile_source() gained an opt-in `annotate_c_lines` kwarg. When on, each
emitted asm line that originated from a C statement carries a trailing `# @c:N`
comment (N = the 1-based C source line). The marker is a comment, so an
annotated .toys assembles to the IDENTICAL memory image as the plain one.

What these tests pin down:
  1. default (annotate_c_lines=False) output has no `@c:` marker at all;
  2. with it on, a statement's asm lines carry the correct `# @c:N`, while
     generated header / data / blank lines carry none;
  3. the annotated text assembles to the same mem image as the plain text
     (the comment is inert);
  4. all of the above for BOTH toycc and minicc.
"""

import re

import pytest

from pytoy.assembler import assemble
from pytoy import compiler as toycc
from pytoy import minicc


# A tiny multi-statement program with one statement per line, so the expected
# C line of each statement is obvious from its position in the source.
PROG = """\
int main(void) {
    int x = 5;
    int y = x + 3;
    return y;
}
"""
#    line 1: int main(void) {
#    line 2: int x = 5;
#    line 3: int y = x + 3;
#    line 4: return y;


def _marker_lines(asm):
    """{C line N: [asm lines tagged @c:N]} for every annotated line."""
    out = {}
    for ln in asm.splitlines():
        m = re.search(r"# .*@c:(\d+)", ln)
        if m:
            out.setdefault(int(m.group(1)), []).append(ln)
    return out


def _mem(asm):
    mem, _listing, _syms, _data, errors, _ds = assemble(asm)
    assert errors == [], f"assembler errors: {errors}\n{asm}"
    return mem


# Each compiler is exercised through the same checks via its compile_source.
COMPILERS = {
    "toycc": toycc.compile_source,
    "minicc": minicc.compile_source,
}


@pytest.mark.parametrize("name", sorted(COMPILERS))
def test_default_has_no_annotation(name):
    """The default path must stay byte-for-byte the plain output: no `@c:`."""
    asm = COMPILERS[name](PROG, "t")
    assert "@c:" not in asm


@pytest.mark.parametrize("name", sorted(COMPILERS))
def test_annotation_tags_the_right_lines(name):
    """Each C statement's asm lines carry its C line; header/blank lines don't."""
    asm = COMPILERS[name](PROG, "t", annotate_c_lines=True)
    by_line = _marker_lines(asm)

    # Statements live on C lines 2, 3, 4 (the `int main` header line 1 and the
    # closing brace have no emitted statement asm).
    assert set(by_line) == {2, 3, 4}, by_line

    # `int x = 5;` (line 2): a load of the constant 5 and a store into x.
    tagged2 = " ".join(by_line[2])
    assert "load" in tagged2 and "5" in tagged2
    assert any("store" in ln for ln in by_line[2])

    # `return y;` (line 4): must include the halt.
    assert any("stop" in ln for ln in by_line[4])

    # Nothing before the first statement is annotated: the generated banner and
    # the blank line under it have no C origin.
    head = asm.splitlines()
    assert "@c:" not in head[0]       # "# Generated by ..."
    assert all("@c:" not in h for h in head[:4])


@pytest.mark.parametrize("name", sorted(COMPILERS))
def test_data_section_not_annotated(name):
    """Data bytes (labels after the data marker) never get a `@c:` tag."""
    asm = COMPILERS[name](PROG, "t", annotate_c_lines=True)
    lines = asm.splitlines()
    # find the data section: minicc writes "# data"; toycc writes the assembler
    # DATA_MARKER. Both are plain `#`-comment lines containing the word "data".
    data_start = next(i for i, ln in enumerate(lines)
                      if ln.strip().startswith("#") and "data" in ln.lower())
    for ln in lines[data_start:]:
        assert "@c:" not in ln, f"data line annotated: {ln!r}"


@pytest.mark.parametrize("name", sorted(COMPILERS))
def test_annotated_assembles_to_same_image(name):
    """The `# @c:N` comments are inert: same mem image as the plain build."""
    plain = COMPILERS[name](PROG, "t")
    annotated = COMPILERS[name](PROG, "t", annotate_c_lines=True)
    assert _mem(plain) == _mem(annotated)


# ── toycc-only: the harder transforms (functions, recursion, folding) ────────
# toycc rebuilds the AST through fold + CallLifter + a liveness pass + a
# peephole that drops lines; the annotation must survive all of that. minicc has
# none of these passes, so these cases are toycc-specific.

TOYCC_CASES = [
    # (label, source, opts)
    ("funccall",
     "int add(int a, int b) {\n"      # line 1
     "    return a + b;\n"            # line 2
     "}\n"                            # line 3
     "int main(void) {\n"            # line 4
     "    int r = add(4, 5);\n"       # line 5
     "    return r;\n"                # line 6
     "}\n",
     None),
    ("recursive",
     "int f(int n) {\n"               # line 1
     "    if (n == 0) return 0;\n"    # line 2
     "    return f(n - 1) + 1;\n"     # line 3
     "}\n"
     "int main(void) {\n"
     "    return f(3);\n"
     "}\n",
     None),
    ("folded",
     "int main(void) {\n"
     "    int x = 3 + 4;\n"
     "    int y = x * 2;\n"
     "    return y;\n"
     "}\n",
     toycc.Opts.all_on()),
]


@pytest.mark.parametrize("label,src,opts", TOYCC_CASES,
                         ids=[c[0] for c in TOYCC_CASES])
def test_toycc_transforms_preserve_annotation(label, src, opts):
    plain = toycc.compile_source(src, "t", opts=opts)
    annotated = toycc.compile_source(src, "t", opts=opts, annotate_c_lines=True)
    # default clean
    assert "@c:" not in plain
    # inert: identical image
    assert _mem(plain) == _mem(annotated)
    # something got annotated (the transforms didn't lose the mapping entirely)
    assert "@c:" in annotated


def test_toycc_recursive_save_restore_lines_point_at_call():
    """In the recursive f, the expanded call sequence (push/assign/setmark/
    call_jump/pop) must carry the C line of the statement that made the call —
    `return f(n - 1) + 1;` on line 3 — proving the line survived CallLifter's
    call-site expansion and the liveness pass."""
    src = ("int f(int n) {\n"
           "    if (n == 0) return 0;\n"
           "    return f(n - 1) + 1;\n"     # line 3: the recursive call
           "}\n"
           "int main(void) {\n"
           "    return f(3);\n"             # line 6: main's call
           "}\n")
    asm = toycc.compile_source(src, "t", annotate_c_lines=True)
    by_line = _marker_lines(asm)
    # The recursive call's setmark / call_jump land on line 3.
    tagged3 = " ".join(by_line.get(3, []))
    assert "f__mark" in tagged3 or "f__body" in tagged3, by_line


# ── the GUI entry point (simulator._compile_c) ───────────────────────────────

@pytest.mark.parametrize("name", sorted(COMPILERS))
def test_gui_entry_point_annotation_flag(name):
    """simulator._compile_c (what the Examples browser calls) threads the flag to
    either compiler and still yields the same mem image either way."""
    from pytoy.simulator import _compile_c
    src = "int main(void) {\n    int x = 5;\n    return x;\n}\n"
    plain = _compile_c(src, name, "p.toyc")
    annotated = _compile_c(src, name, "p.toyc", annotate_c_lines=True)
    assert "@c:" not in plain
    assert "@c:" in annotated
    assert _mem(plain) == _mem(annotated)
