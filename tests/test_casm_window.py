"""Tests for the C | asm view (the C-vs-asm window + its line map).

Two levels:

  1. parse_c_line_map (pure, no Qt): the `# @c:N` markers of an annotated build
     parse into a correct BIDIRECTIONAL map — a specific C line maps to the
     expected asm rows, and the inverse agrees.

  2. The CAsmDialog itself, built headlessly: both panels populated (C left,
     asm right), clicking/selecting a C line highlights exactly its mapped asm
     rows, and OK loads the program into the simulator at step 0.

The GUI classes live inside gui_main()'s closure (CAsmDialog, ToyDebugger), so
we build a real debugger window headlessly — recording the windows that already
exist first and picking the NEW ToyDebugger, as the other GUI tests do, to avoid
isolation flakiness — and capture the CAsmDialog by monkeypatching QDialog.exec.

Skipped if PySide6 is missing; forces QT_QPA_PLATFORM=offscreen.
"""

import os
import re

import pytest

os.environ.setdefault("QT_QPA_PLATFORM", "offscreen")

from pytoy.simulator import parse_c_line_map, _compile_c


# A tiny program with one statement per C line, so the expected mapping is
# obvious from the source positions.
PROG = """\
int main(void) {
    int x = 5;
    int y = x + 3;
    return y;
}
"""
#    line 1: int main(void) {
#    line 2: int x = 5;
#    line 3: int y = x + 3;
#    line 4: return y;


# ── 1. parse_c_line_map: bidirectional correctness (pure) ────────────────────

def test_parse_c_line_map_is_bidirectional():
    asm = _compile_c(PROG, "toycc", "p.toyc", annotate_c_lines=True)
    c_to_asm, asm_to_c = parse_c_line_map(asm)

    asm_lines = asm.splitlines()

    # Every mapped asm row actually carries that C line's marker, and the
    # inverse map agrees on every entry.
    for c_line, rows in c_to_asm.items():
        assert rows == sorted(rows)                 # rows kept sorted
        for row in rows:
            assert re.search(rf"@c:{c_line}\b", asm_lines[row]), asm_lines[row]
            assert asm_to_c[row] == c_line

    # The inverse covers exactly the rows the forward map lists.
    all_rows = {r for rows in c_to_asm.values() for r in rows}
    assert set(asm_to_c) == all_rows

    # Statements live on C lines 2, 3, 4 (the `int main` header and closing
    # brace emit no statement asm), matching the annotation test's expectation.
    assert set(c_to_asm) == {2, 3, 4}

    # `int x = 5;` (line 2) maps to >1 asm row (a load and a store, at least),
    # proving the one-C-line -> many-asm-lines case.
    assert len(c_to_asm[2]) >= 2
    tagged2 = " ".join(asm_lines[r] for r in c_to_asm[2])
    assert "load" in tagged2 and "store" in tagged2

    # Header/data rows carry no marker, so they are absent from the map.
    assert "@c:" not in asm_lines[0]          # "# Generated by ..."
    assert 0 not in asm_to_c


def test_parse_c_line_map_empty_without_markers():
    """A plain (unannotated) build has no markers -> both maps empty."""
    asm = _compile_c(PROG, "toycc", "p.toyc")      # annotate off
    c_to_asm, asm_to_c = parse_c_line_map(asm)
    assert c_to_asm == {} and asm_to_c == {}


# ── 2. the CAsmDialog, built headlessly ──────────────────────────────────────

pytest.importorskip("PySide6")


def _build_window():
    """Construct a real ToyDebugger offscreen and return (app, win). Records the
    windows that already exist and returns the NEW ToyDebugger, so a lingering
    window from another GUI test can't be mistaken for this one."""
    from PySide6.QtWidgets import QApplication
    from PySide6.QtCore import Qt
    app = QApplication.instance() or QApplication([])
    from pytoy import simulator

    before = set(app.topLevelWidgets())

    mem = [0] * 256
    listing = [(a, [mem[a]], "", True) for a in range(256)]

    orig_exec = QApplication.exec
    QApplication.exec = lambda self: 0
    try:
        simulator.gui_main(mem, listing, {}, set(range(256)),
                           code_guard=None, has_source=False)
    finally:
        QApplication.exec = orig_exec

    new = [w for w in app.topLevelWidgets()
           if w not in before and w.__class__.__name__ == "ToyDebugger"]
    assert new, "ToyDebugger window was not constructed"
    win = new[-1]
    win.setAttribute(Qt.WA_DeleteOnClose, True)
    return app, win


def _capture_dialog(win, c_text, compiler, path, accept):
    """Drive _compile_and_show_casm but capture the CAsmDialog instead of
    opening it modally. `accept` decides the fake exec() return (Accepted ->
    the OK-load path runs). Returns the captured dialog."""
    from PySide6.QtWidgets import QDialog

    captured = {}
    orig_exec = QDialog.exec

    def fake_exec(self):
        captured["dlg"] = self
        return QDialog.Accepted if accept else QDialog.Rejected

    QDialog.exec = fake_exec
    try:
        win._compile_and_show_casm(c_text, compiler, path)
    finally:
        QDialog.exec = orig_exec
    assert "dlg" in captured, "CAsmDialog was not constructed"
    return captured["dlg"]


def test_casm_window_panels_and_highlight():
    app, win = _build_window()
    try:
        dlg = _capture_dialog(win, PROG, "toycc", "p.toyc", accept=False)

        # Both panels populated: C text on the left, asm on the right.
        c_shown = dlg.c_view.toPlainText()
        asm_shown = dlg.asm_view.toPlainText()
        assert "int main(void)" in c_shown
        assert "int x = 5;" in c_shown
        assert "load" in asm_shown and "stop" in asm_shown
        # the markers stay in the displayed asm (we keep the comments)
        assert "@c:" in asm_shown

        # Selecting C line 2 highlights exactly the asm rows the map says.
        c_to_asm, _ = parse_c_line_map(dlg._asm_text)
        dlg.select_c_line(2)
        assert dlg.highlighted_asm_rows() == c_to_asm[2]
        assert len(dlg.highlighted_asm_rows()) >= 2    # one C line -> many asm

        # Selecting a different C line switches the highlight set.
        dlg.select_c_line(4)
        assert dlg.highlighted_asm_rows() == c_to_asm[4]

        # Selecting a C line with no asm origin (the closing brace / header)
        # highlights nothing.
        dlg.select_c_line(1)
        assert dlg.highlighted_asm_rows() == []
        dlg.close()
    finally:
        win.close()
        app.processEvents()


def test_casm_window_asm_click_maps_back_to_c():
    app, win = _build_window()
    try:
        dlg = _capture_dialog(win, PROG, "toycc", "p.toyc", accept=False)
        c_to_asm, asm_to_c = parse_c_line_map(dlg._asm_text)

        # Pick a real asm row and its C line; the dialog's asm->c resolution
        # must select that same C line (lighting up all its sibling asm rows).
        asm_row = c_to_asm[2][0]
        dlg.select_c_line(asm_to_c[asm_row])
        assert dlg._sel_c_line == 2
        assert dlg.highlighted_asm_rows() == c_to_asm[2]
        dlg.close()
    finally:
        win.close()
        app.processEvents()


def test_load_toyc_routes_through_window_and_prefers_toycc():
    """A .toyc opened via the Load dialog goes through _load_toyc -> the C|asm
    window (not a direct load), and when both compilers accept the file toycc
    (the full one) is chosen. Uses a real example file."""
    from PySide6.QtWidgets import QDialog
    app, win = _build_window()
    try:
        from pytoy.examples_index import list_examples, _detect_compilers
        # Find a C example both compilers accept, so the toycc-preference matters.
        both = next(e for e in list_examples()
                    if e.category == "c"
                    and set(_detect_compilers(e.path)) >= {"minicc", "toycc"})

        captured = {}
        orig_exec = QDialog.exec

        def fake_exec(self):
            captured["dlg"] = self
            self._on_ok()
            return QDialog.Accepted

        QDialog.exec = fake_exec
        try:
            win._load_toyc(both.path)
        finally:
            QDialog.exec = orig_exec

        dlg = captured["dlg"]
        assert "toycc" in dlg.windowTitle()          # preferred over minicc
        assert any(b != 0 for b in win.mem)           # OK loaded the program
        assert win._current_path == both.path
        dlg.close()
    finally:
        win.close()
        app.processEvents()


def test_reload_keeps_chosen_compiler():
    """Loading a C example with minicc records the compiler; a Reload of the same
    .toyc must reuse minicc and NOT re-detect (which would silently switch to the
    toycc-preferred default when both compilers accept the file)."""
    from PySide6.QtWidgets import QDialog
    app, win = _build_window()
    try:
        from pytoy.examples_index import list_examples, _detect_compilers
        both = next(e for e in list_examples()
                    if e.category == "c"
                    and set(_detect_compilers(e.path)) >= {"minicc", "toycc"})

        # First load: pick minicc explicitly (as the Examples browser would) and
        # accept the C|asm window, which records _current_compiler.
        orig_exec = QDialog.exec

        def ok_exec(self):
            self._on_ok()
            return QDialog.Accepted

        QDialog.exec = ok_exec
        try:
            win._compile_and_show_casm(open(both.path).read(), "minicc",
                                       both.path)
            assert win._current_compiler == "minicc"
            assert win._current_path == both.path

            # Now Reload: _load_path -> _load_toyc must reuse minicc, so the
            # re-opened C|asm window is still minicc (no silent toycc switch).
            seen = {}

            def capture_exec(self):
                seen["compiler"] = self.windowTitle()
                self._on_ok()
                return QDialog.Accepted

            QDialog.exec = capture_exec
            win._load_path(both.path)
        finally:
            QDialog.exec = orig_exec

        assert "minicc" in seen["compiler"], \
            f"Reload switched compiler: {seen['compiler']}"
        assert win._current_compiler == "minicc"
    finally:
        win.close()
        app.processEvents()


def test_casm_window_ok_loads_program():
    app, win = _build_window()
    try:
        # accept=True -> the fake exec returns Accepted, so _compile_and_show_casm
        # runs the OK-load path. But the dialog's own _on_ok (the real load) only
        # runs on a genuine button press; drive it explicitly to load the asm.
        dlg = _capture_dialog(win, PROG, "toycc", "p.toyc", accept=True)
        dlg._on_ok()

        # Program loaded: memory populated and the debugger is at step 0.
        assert any(b != 0 for b in win.mem), "OK did not load a program"
        assert win.step_count == 0
        # _compile_and_show_casm's Accepted branch records the source path.
        assert win._current_path == "p.toyc"
        assert win.has_source is True
        dlg.close()
    finally:
        win.close()
        app.processEvents()
